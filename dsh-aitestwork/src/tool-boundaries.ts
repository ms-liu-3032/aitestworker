export function unclassifiedTool(name: string): string | undefined {
  return name.startsWith('aitestwork_') && !Object.hasOwn(TOOL_BOUNDARIES, name)
    ? `AITestWork 工具 ${name} 未纳入规则清单；拒绝执行，请更新插件策略和测试` : undefined
}
